import { createHash, randomBytes } from 'node:crypto';

/** Loose UUID shape check (any version, any case). */
export const UUID_RE = /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/;

function format(bytes: Buffer): string {
  const h = bytes.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}

/** RFC 9562 UUIDv7: 48-bit unix ms timestamp + random bits. */
export function uuidv7(now: number = Date.now()): string {
  const b = randomBytes(16);
  let ts = BigInt(now);
  for (let i = 5; i >= 0; i--) {
    b[i] = Number(ts & 0xffn);
    ts >>= 8n;
  }
  b[6] = (b[6]! & 0x0f) | 0x70;
  b[8] = (b[8]! & 0x3f) | 0x80;
  return format(b);
}

/**
 * Deterministic UUID (version 8, "custom") derived from a string key.
 * Used where retries must map to the same id, e.g. sync conflict copies.
 */
export function uuidFromKey(key: string): string {
  const b = createHash('sha256').update(key).digest().subarray(0, 16);
  b[6] = (b[6]! & 0x0f) | 0x80;
  b[8] = (b[8]! & 0x3f) | 0x80;
  return format(Buffer.from(b));
}
